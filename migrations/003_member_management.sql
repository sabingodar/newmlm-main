CREATE TABLE member_profiles (
  user_id BIGINT PRIMARY KEY REFERENCES records(id),
  first_name TEXT NOT NULL DEFAULT '', last_name TEXT NOT NULL DEFAULT '',
  address TEXT NOT NULL DEFAULT '', city TEXT NOT NULL DEFAULT '', state TEXT NOT NULL DEFAULT '', postal_code TEXT NOT NULL DEFAULT '', country TEXT NOT NULL DEFAULT '',
  email_verified BOOLEAN, mobile_verified BOOLEAN,
  kyc_status TEXT NOT NULL DEFAULT 'Unknown' CHECK(kyc_status IN ('Unknown','Pending','Verified','Rejected')),
  affiliate_rank_id BIGINT REFERENCES records(id), referrer_id BIGINT REFERENCES records(id), parent_id BIGINT REFERENCES records(id),
  position TEXT CHECK(position IN ('Left','Right')),
  notes TEXT NOT NULL DEFAULT '', ban_reason TEXT NOT NULL DEFAULT '',
  permissions JSONB NOT NULL DEFAULT '["profile","orders","deposits","withdrawals","ledger","notifications"]',
  CHECK(referrer_id IS NULL OR referrer_id<>user_id), CHECK(parent_id IS NULL OR parent_id<>user_id)
);
CREATE UNIQUE INDEX member_placement_slot ON member_profiles(parent_id,position) WHERE parent_id IS NOT NULL AND position IS NOT NULL;
CREATE INDEX member_referrer ON member_profiles(referrer_id);
CREATE INDEX member_parent ON member_profiles(parent_id);
CREATE UNIQUE INDEX member_username ON records(lower(COALESCE(NULLIF(data->>'username',''),NULLIF(data->>'legacyUsername','')))) WHERE kind='users';
CREATE TABLE member_accounts (
  user_id BIGINT PRIMARY KEY REFERENCES records(id),
  opening_balance NUMERIC(20,2) NOT NULL DEFAULT 0,
  balance NUMERIC(20,2) NOT NULL DEFAULT 0 CHECK(balance>=0)
);
CREATE TABLE member_ledger (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES member_accounts(user_id),
  direction TEXT NOT NULL CHECK(direction IN ('Credit','Debit')),
  amount NUMERIC(20,2) NOT NULL CHECK(amount>0), balance_after NUMERIC(20,2) NOT NULL CHECK(balance_after>=0),
  reason TEXT NOT NULL, request_id TEXT NOT NULL, actor TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(user_id,request_id)
);
CREATE INDEX member_ledger_user ON member_ledger(user_id,id DESC);
CREATE FUNCTION protect_member_ledger() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'Member ledger entries are append-only'; END $$;
CREATE TRIGGER member_ledger_immutable BEFORE UPDATE OR DELETE ON member_ledger FOR EACH ROW EXECUTE FUNCTION protect_member_ledger();
CREATE TABLE member_credentials (
  user_id BIGINT PRIMARY KEY REFERENCES records(id), salt TEXT NOT NULL, password_hash TEXT NOT NULL, version TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE member_sessions (
  token TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES member_credentials(user_id), credential_version TEXT NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX member_sessions_expiry ON member_sessions(expires_at);
CREATE TABLE member_login_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES records(id),
  ip TEXT NOT NULL, user_agent TEXT NOT NULL, success BOOLEAN NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX member_login_user ON member_login_history(user_id,id DESC);
CREATE TABLE member_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES records(id),
  title TEXT NOT NULL, message TEXT NOT NULL, actor TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX member_notification_user ON member_notifications(user_id,id DESC);
ALTER TABLE audit ADD COLUMN details JSONB NOT NULL DEFAULT '{}';
CREATE FUNCTION initialize_member() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.kind='users' THEN
    INSERT INTO member_profiles(user_id,country) VALUES(NEW.id,COALESCE(NEW.data->>'country',''));
    INSERT INTO member_accounts(user_id,opening_balance,balance) VALUES(NEW.id,COALESCE((NEW.data->>'legacyBalance')::numeric,0),COALESCE((NEW.data->>'legacyBalance')::numeric,0));
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER initialize_member_after_insert AFTER INSERT ON records FOR EACH ROW EXECUTE FUNCTION initialize_member();
