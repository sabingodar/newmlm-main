CREATE TABLE rank_reward_awards (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES records(id),rank_id BIGINT NOT NULL REFERENCES records(id),
 amount NUMERIC(20,2) NOT NULL CHECK(amount>=0),ledger_id BIGINT UNIQUE REFERENCES member_ledger(id),
 rule_snapshot JSONB NOT NULL,metrics_snapshot JSONB NOT NULL,actor TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),UNIQUE(user_id,rank_id)
);
CREATE TRIGGER rank_reward_awards_immutable BEFORE UPDATE OR DELETE ON rank_reward_awards FOR EACH ROW EXECUTE FUNCTION protect_member_ledger();
UPDATE records SET data=data||jsonb_build_object(
 'minPurchase',COALESCE((data->>'minPurchase')::numeric,NULLIF(regexp_replace(data->'source'->'cells'->>4,'[^0-9.]','','g'),'')::numeric,0),
 'earthBv',COALESCE((data->>'earthBv')::numeric,(data->>'bv')::numeric,0),
 'skyBv',COALESCE((data->>'skyBv')::numeric,NULLIF(regexp_replace(data->'source'->'cells'->>6,'[^0-9.]','','g'),'')::numeric,(data->>'bv')::numeric,0)
) WHERE kind='ranks';
CREATE INDEX rank_completed_order_owner ON records((data->>'userId')) WHERE kind='orders' AND data->>'status'='Delivered' AND data->>'paymentStatus'='Paid' AND COALESCE(data->>'legacyReadOnly','false')<>'true';
