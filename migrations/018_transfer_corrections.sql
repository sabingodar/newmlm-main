CREATE TABLE inventory_transfer_edits (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 transfer_id BIGINT NOT NULL REFERENCES inventory_transfers(id),
 status TEXT NOT NULL DEFAULT 'Pending' CHECK(status IN ('Pending','Approved','Rejected')),
 original_items JSONB NOT NULL,proposed_items JSONB NOT NULL,
 reason TEXT NOT NULL,requested_by TEXT NOT NULL,request_key TEXT NOT NULL,fingerprint TEXT NOT NULL,
 reviewed_by TEXT,review_remarks TEXT NOT NULL DEFAULT '',created_at TIMESTAMPTZ NOT NULL DEFAULT now(),reviewed_at TIMESTAMPTZ,
 UNIQUE(requested_by,request_key)
);
CREATE UNIQUE INDEX inventory_transfer_one_pending_edit ON inventory_transfer_edits(transfer_id) WHERE status='Pending';
ALTER TABLE inventory_transfers ADD COLUMN approved_edit_id BIGINT REFERENCES inventory_transfer_edits(id) DEFERRABLE INITIALLY DEFERRED;
CREATE FUNCTION protect_transfer_edit_history() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Transfer edit history cannot be deleted'; END IF;
 IF OLD.status<>'Pending' OR (to_jsonb(NEW)-ARRAY['status','reviewed_by','review_remarks','reviewed_at']) IS DISTINCT FROM (to_jsonb(OLD)-ARRAY['status','reviewed_by','review_remarks','reviewed_at']) THEN RAISE EXCEPTION 'Transfer edit details are immutable'; END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER transfer_edit_history BEFORE UPDATE OR DELETE ON inventory_transfer_edits FOR EACH ROW EXECUTE FUNCTION protect_transfer_edit_history();
