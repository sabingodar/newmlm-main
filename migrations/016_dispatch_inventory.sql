CREATE TABLE inventory_proofs (
 id UUID PRIMARY KEY,name TEXT NOT NULL,mime_type TEXT NOT NULL,
 content BYTEA NOT NULL CHECK(octet_length(content)>0 AND octet_length(content)<=5242880),
 owner_username TEXT NOT NULL,created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE inventory_transfers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 center_id BIGINT NOT NULL REFERENCES records(id),reference TEXT NOT NULL UNIQUE,
 request_key TEXT NOT NULL,fingerprint TEXT NOT NULL,actor TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'Sent' CHECK(status IN ('Sent','Received','Cancelled')),
 remarks TEXT NOT NULL DEFAULT '',proof_id UUID REFERENCES inventory_proofs(id),
 center_snapshot JSONB NOT NULL,received_by TEXT,received_at TIMESTAMPTZ,
 receipt_remarks TEXT NOT NULL DEFAULT '',receipt_proof_id UUID REFERENCES inventory_proofs(id),
 version INTEGER NOT NULL DEFAULT 1,created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(actor,request_key)
);
CREATE TABLE inventory_transfer_lines (
 transfer_id BIGINT NOT NULL REFERENCES inventory_transfers(id),product_id BIGINT NOT NULL REFERENCES records(id),
 quantity INTEGER NOT NULL CHECK(quantity>0),snapshot JSONB NOT NULL,
 PRIMARY KEY(transfer_id,product_id)
);
CREATE TABLE inventory_center_stock (
 center_id BIGINT NOT NULL REFERENCES records(id),product_id BIGINT NOT NULL REFERENCES records(id),
 on_hand BIGINT NOT NULL DEFAULT 0 CHECK(on_hand>=0),reserved BIGINT NOT NULL DEFAULT 0 CHECK(reserved>=0 AND reserved<=on_hand),
 version INTEGER NOT NULL DEFAULT 1,PRIMARY KEY(center_id,product_id)
);
CREATE TABLE inventory_order_allocations (
 order_id BIGINT NOT NULL REFERENCES records(id),product_id BIGINT NOT NULL REFERENCES records(id),
 center_id BIGINT REFERENCES records(id),original_quantity INTEGER NOT NULL CHECK(original_quantity>0),
 remaining INTEGER NOT NULL CHECK(remaining>=0 AND remaining<=original_quantity),central_managed BOOLEAN NOT NULL,
 PRIMARY KEY(order_id,product_id)
);
CREATE TABLE inventory_dispatches (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,order_id BIGINT NOT NULL REFERENCES records(id),
 center_id BIGINT REFERENCES records(id),reference TEXT NOT NULL UNIQUE,
 request_key TEXT NOT NULL,fingerprint TEXT NOT NULL,actor TEXT NOT NULL,
 remarks TEXT NOT NULL DEFAULT '',proof_id UUID REFERENCES inventory_proofs(id),snapshot JSONB NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),UNIQUE(actor,request_key)
);
CREATE TABLE inventory_dispatch_lines (
 dispatch_id BIGINT NOT NULL REFERENCES inventory_dispatches(id),product_id BIGINT NOT NULL REFERENCES records(id),
 quantity INTEGER NOT NULL CHECK(quantity>0),snapshot JSONB NOT NULL,
 PRIMARY KEY(dispatch_id,product_id)
);
CREATE TABLE inventory_movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,product_id BIGINT NOT NULL REFERENCES records(id),
 center_id BIGINT REFERENCES records(id),location_key TEXT NOT NULL,
 quantity_delta BIGINT NOT NULL,reserved_delta BIGINT NOT NULL DEFAULT 0,
 quantity_after BIGINT NOT NULL CHECK(quantity_after>=0),reserved_after BIGINT NOT NULL DEFAULT 0 CHECK(reserved_after>=0),
 reference TEXT NOT NULL,reason TEXT NOT NULL,actor TEXT NOT NULL DEFAULT 'system',details JSONB NOT NULL DEFAULT '{}',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),UNIQUE(product_id,location_key,reference),
 CHECK((center_id IS NULL AND location_key='central' AND reserved_after=0 AND reserved_delta=0) OR (center_id IS NOT NULL AND location_key='center:'||center_id::text AND reserved_after<=quantity_after))
);
CREATE INDEX inventory_transfers_center ON inventory_transfers(center_id,status,id DESC);
CREATE INDEX inventory_dispatches_order ON inventory_dispatches(order_id,id DESC);
CREATE INDEX inventory_movements_center ON inventory_movements(center_id,product_id,id DESC);
CREATE INDEX inventory_allocations_center ON inventory_order_allocations(center_id,product_id) WHERE remaining>0;
CREATE TRIGGER inventory_movement_immutable BEFORE UPDATE OR DELETE ON inventory_movements FOR EACH ROW EXECUTE FUNCTION protect_member_ledger();
CREATE TRIGGER inventory_transfer_line_immutable BEFORE UPDATE OR DELETE ON inventory_transfer_lines FOR EACH ROW EXECUTE FUNCTION protect_member_ledger();
CREATE TRIGGER inventory_dispatch_line_immutable BEFORE UPDATE OR DELETE ON inventory_dispatch_lines FOR EACH ROW EXECUTE FUNCTION protect_member_ledger();
CREATE TRIGGER inventory_dispatch_immutable BEFORE UPDATE OR DELETE ON inventory_dispatches FOR EACH ROW EXECUTE FUNCTION protect_member_ledger();
