CREATE TABLE administrators (
  username TEXT PRIMARY KEY,
  salt TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  credential_version TEXT NOT NULL
);
CREATE TABLE sessions (
  token TEXT PRIMARY KEY,
  username TEXT NOT NULL REFERENCES administrators(username) ON DELETE CASCADE,
  credential_version TEXT NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX sessions_expiry ON sessions(expires_at);
CREATE TABLE records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL CHECK (kind IN ('users','affiliates','plans','products','orders','deposits','withdrawals','tickets','leads','ranks','pins','centers','tasks')),
  data JSONB NOT NULL CHECK (jsonb_typeof(data)='object'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  version INTEGER NOT NULL DEFAULT 1,
  CHECK (kind <> 'products' OR (data->>'stock')::numeric >= 0)
);
CREATE INDEX records_kind_created ON records(kind,created_at DESC,id DESC);
CREATE INDEX records_kind_status ON records(kind,(data->>'status'));
CREATE INDEX records_legacy_id ON records(kind,(data->>'legacyId'));
CREATE INDEX records_document ON records USING GIN(data jsonb_path_ops);
CREATE UNIQUE INDEX unique_pin_code ON records((data->>'code')) WHERE kind='pins';
CREATE TABLE audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action TEXT NOT NULL,
  kind TEXT NOT NULL,
  record_id BIGINT NOT NULL REFERENCES records(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX audit_created ON audit(created_at DESC,id DESC);
CREATE TABLE settings (id SMALLINT PRIMARY KEY CHECK (id=1), data JSONB NOT NULL);
CREATE TABLE archive (kind TEXT PRIMARY KEY, data JSONB NOT NULL CHECK(jsonb_typeof(data)='array'));
CREATE TABLE data_imports (name TEXT PRIMARY KEY, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE import_staging (kind TEXT PRIMARY KEY, data JSONB NOT NULL CHECK(jsonb_typeof(data)='array'));
CREATE TABLE login_attempts (ip TEXT PRIMARY KEY, attempts INTEGER NOT NULL, expires_at TIMESTAMPTZ NOT NULL);
